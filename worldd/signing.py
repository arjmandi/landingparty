"""World-owned Ed25519 HTTP Message Signatures (RFC 9421).

A configured HTTPS Signature-Agent directory URL identifies this signing key.
Keys stay in the private data directory. Signing never changes response content.
"""

from __future__ import annotations

import base64
import hashlib
import json
import os
import time
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey, Ed25519PublicKey


def _b64url(value: bytes) -> str:
    return base64.urlsafe_b64encode(value).rstrip(b"=").decode()


class WorldSigner:
    def __init__(self, data_dir: Path, identity_url: str, *, key: Ed25519PrivateKey | None = None):
        parsed = urlsplit(identity_url)
        if (
            parsed.scheme != "https"
            or not parsed.hostname
            or parsed.username
            or parsed.password
            or parsed.fragment
        ):
            raise ValueError(
                "Signature-Agent identity must be a credential-free HTTPS directory URL"
            )
        self.identity_url = identity_url
        directory = Path(data_dir) / "keys"
        directory.mkdir(parents=True, exist_ok=True, mode=0o700)
        path = directory / "http-signing.pem"
        if path.is_symlink() or (path.exists() and path.stat().st_mode & 0o077):
            raise ValueError("World signing keys must be private mode-0600 regular files")
        if key is None and path.exists():
            key = serialization.load_pem_private_key(path.read_bytes(), password=None)
            if not isinstance(key, Ed25519PrivateKey):
                raise ValueError("The signing key must be Ed25519")
        elif key is None:
            key = Ed25519PrivateKey.generate()
            fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(fd, "wb") as stream:
                stream.write(
                    key.private_bytes(
                        serialization.Encoding.PEM,
                        serialization.PrivateFormat.PKCS8,
                        serialization.NoEncryption(),
                    )
                )
        self.key = key
        public = key.public_key().public_bytes(
            serialization.Encoding.Raw, serialization.PublicFormat.Raw
        )
        self.jwk = {"crv": "Ed25519", "kty": "OKP", "x": _b64url(public)}
        self.key_id = _b64url(
            hashlib.sha256(
                json.dumps(self.jwk, sort_keys=True, separators=(",", ":")).encode()
            ).digest()
        )

    def directory(self) -> dict:
        return {"keys": [{**self.jwk, "kid": self.key_id, "alg": "EdDSA", "use": "sig"}]}

    def sign(
        self, method: str, url: str, *, timestamp: int | None = None, ttl: int = 60
    ) -> dict[str, str]:
        parts = urlsplit(url)
        url = urlunsplit((parts.scheme, parts.netloc, parts.path or "/", parts.query, ""))
        created = int(time.time()) if timestamp is None else int(timestamp)
        if not 1 <= ttl <= 300:
            raise ValueError("HTTP signature TTL must be between one and 300 seconds")
        authority = urlsplit(url).netloc.lower()
        parameters = '("@method" "@authority" "@target-uri" "signature-agent")' + (
            f';created={created};expires={created + ttl};keyid="{self.key_id}";alg="ed25519";tag="web-bot-auth"'
        )
        agent = json.dumps(self.identity_url, ensure_ascii=True)
        base = (
            f'"@method": {method.upper()}\n"@authority": {authority}\n'
            f'"@target-uri": {url}\n"signature-agent": {agent}\n'
            f'"@signature-params": {parameters}'
        ).encode()
        signature = base64.b64encode(self.key.sign(base)).decode()
        return {
            "Signature-Agent": agent,
            "Signature-Input": "sig1=" + parameters,
            "Signature": f"sig1=:{signature}:",
        }

    def verify(self, method: str, url: str, headers: dict, *, timestamp: int | None = None) -> bool:
        """Verify signatures generated by this world, including creation/expiry."""
        import re

        try:
            values = {key.lower(): value for key, value in headers.items()}
            parameters = values["signature-input"].removeprefix("sig1=")
            created = int(re.search(r";created=(\d+)", parameters)[1])
            expires = int(re.search(r";expires=(\d+)", parameters)[1])
            clock = int(time.time()) if timestamp is None else timestamp
            if not created <= clock <= expires or expires - created > 300:
                return False
            expected = self.sign(method, url, timestamp=created, ttl=expires - created)
            if (
                expected["Signature-Input"] != values["signature-input"]
                or expected["Signature-Agent"] != values["signature-agent"]
            ):
                return False
            return expected["Signature"] == values["signature"]
        except (KeyError, ValueError, TypeError, AttributeError):
            return False


def verify_public_signature(public_key: bytes, signature: bytes, signature_base: bytes) -> bool:
    try:
        Ed25519PublicKey.from_public_bytes(public_key).verify(signature, signature_base)
        return True
    except (InvalidSignature, ValueError):
        return False
